#!/usr/bin/env python3
"""
Builds the effects atlas (client/src/assets/fx-atlas.png) and its frame table (client/src/game/fx-atlas.ts)
from Kenney's CC0 "Particle Pack" and "Smoke Particles" (https://kenney.nl) and the explosion and hit sparks of
Ansimuz's CC0 "Warped City" (https://ansimuz.itch.io/warped-city). CC0: free for commercial use, no credit
required; we credit both in ASSETS.md anyway.

Usage:  python3 tools/build-fx-atlas.py <folder holding particlePack_1.1 and smokeparticleassets> <"warped city files" folder>
Needs:  Pillow (pip install pillow). Then run prettier on client/src/game/fx-atlas.ts.
        The atlas is committed, so the game build never needs Python.

Kenney's pictures are shrunk to a 64 px cell and posterised (few alpha and colour steps), so in game it reads as
pixel art. Grey pictures become white with their brightness as alpha, so the game can tint them any colour.
"""
import sys
from pathlib import Path

from PIL import Image

CELL = 64
COLS = 8
ROOT = Path(__file__).resolve().parent.parent

# name -> (files, mode): 'colour' keeps the colours, 'white' becomes tintable white, 'pixel' is pixel art that is
# copied as it is (never resampled), centred in its cell, and drawn by the game at whole multiples of its size.
PP = 'particlePack_1.1/PNG (Transparent)/'
SM = 'smokeparticleassets/PNG/'
WC = 'W:Assets/SPRITES/misc/'  # 'W:' = inside the Warped City folder
SETS = {
    'fire': ([f'{SM}Explosion/explosion{i:02d}.png' for i in range(9)], 'colour'),
    'flash': ([f'{SM}Flash/flash{i:02d}.png' for i in range(6)], 'colour'),
    'smoke': ([f'{SM}Black smoke/blackSmoke{i:02d}.png' for i in range(8)], 'colour'),
    'puff': ([f'{SM}White puff/whitePuff{i:02d}.png' for i in range(6)], 'colour'),
    'star': ([f'{PP}star_{i:02d}.png' for i in (6, 7, 8)], 'white'),
    'glow': ([f'{PP}star_05.png'], 'white'),
    'ring': ([f'{PP}circle_03.png'], 'white'),
    'muzzle': ([f'{PP}muzzle_{i:02d}.png' for i in (1, 2, 3, 4)], 'white'),
    'bolt': ([f'{PP}spark_{i:02d}.png' for i in (5, 6)], 'white'),
    'magic': ([f'{PP}magic_{i:02d}.png' for i in (3, 5)], 'white'),
    'dirt': ([f'{PP}dirt_{i:02d}.png' for i in (1, 2, 3)], 'white'),
    'slash': ([f'{PP}slash_{i:02d}.png' for i in (2, 3)], 'white'),
    'blast': ([f'{WC}enemy-explosion/enemy-explosion-{i}.png' for i in range(1, 7)], 'pixel'),
    'hit': ([f'{WC}shot-hit/shot-hit-{i}.png' for i in range(1, 4)], 'pixel'),
}


def step(v: int, n: int) -> int:
    return round(round(v / 255 * (n - 1)) * 255 / (n - 1))


def cell(path: Path, mode: str) -> Image.Image:
    im = Image.open(path).convert('RGBA')
    if mode == 'pixel':
        out = Image.new('RGBA', (CELL, CELL), (0, 0, 0, 0))
        out.paste(im, ((CELL - im.width) // 2, (CELL - im.height) // 2))
        return out
    colour = mode == 'colour'
    im = im.crop(im.getbbox() or (0, 0, im.width, im.height))
    im.thumbnail((CELL - 2, CELL - 2), Image.LANCZOS)
    out = Image.new('RGBA', (CELL, CELL), (0, 0, 0, 0))
    px = im.load()
    for y in range(im.height):
        for x in range(im.width):
            r, g, b, a = px[x, y]
            if not colour:  # white, brightness as alpha
                a = a * max(r, g, b) // 255
                r = g = b = 255
            a = step(a, 6)
            if a < 30:
                a = 0
            px[x, y] = (step(r, 9), step(g, 9), step(b, 9), a)
    out.paste(im, ((CELL - im.width) // 2, (CELL - im.height) // 2))
    return out


def main() -> None:
    if len(sys.argv) < 3:
        sys.exit(__doc__)
    kenney, warped = Path(sys.argv[1]), Path(sys.argv[2])
    cells: list[Image.Image] = []
    table: dict[str, list[int]] = {}
    for name, (files, mode) in SETS.items():
        table[name] = []
        for f in files:
            table[name].append(len(cells))
            cells.append(cell(warped / f[2:] if f.startswith('W:') else kenney / f, mode))
    rows = (len(cells) + COLS - 1) // COLS
    atlas = Image.new('RGBA', (COLS * CELL, rows * CELL), (0, 0, 0, 0))
    for i, c in enumerate(cells):
        atlas.paste(c, ((i % COLS) * CELL, (i // COLS) * CELL))
    out = ROOT / 'client/src/assets'
    out.mkdir(parents=True, exist_ok=True)
    atlas.save(out / 'fx-atlas.png', optimize=True)
    names = ' | '.join(f"'{n}'" for n in table)
    lines = [
        '// Generated by tools/build-fx-atlas.py from Kenney CC0 packs (see ASSETS.md). Do not edit by hand.',
        f'export const FX_CELL = {CELL};',
        f'export const FX_COLS = {COLS};',
        f'export type FxName = {names};',
        '/** Atlas cells of each effect; a cell is FX_CELL px square, numbered row by row. */',
        'export const FX_FRAMES: Readonly<Record<FxName, readonly number[]>> = {',
        *[f'  {n}: [{", ".join(map(str, v))}],' for n, v in table.items()],
        '};',
        '/** Effects whose colours are baked in; the others are white and get tinted. */',
        f"export const FX_COLOURED: ReadonlySet<FxName> = new Set([{', '.join(repr(n) for n, (_, m) in SETS.items() if m != 'white')}]);",
        '/** Pixel art: never smoothed, best drawn at FX_CELL times a whole number. */',
        f"export const FX_PIXEL: ReadonlySet<FxName> = new Set([{', '.join(repr(n) for n, (_, m) in SETS.items() if m == 'pixel')}]);",
        '',
    ]
    (ROOT / 'client/src/game/fx-atlas.ts').write_text('\n'.join(lines))
    print(f'{len(cells)} cells -> {out / "fx-atlas.png"} ({(out / "fx-atlas.png").stat().st_size // 1024} KB)')


if __name__ == '__main__':
    main()
